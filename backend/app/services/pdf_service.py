def generate_notes_pdf(notes_data: list) -> BytesIO:
    """
    Generate a PDF from notes.

    Expected structure:

    [
        {
            "title": "Note 1",
            "content": "My note...",
            "created_at": "2026-08-04"
        }
    ]

    Returns:
        BytesIO containing the generated PDF.
    """

    buffer = BytesIO()
    doc = _create_document(buffer)
    styles = _get_styles()

    story = []

    # Header
    story.append(
        Paragraph(
            "My Notes",
            styles["title"]
        )
    )

    story.append(
        Paragraph(
            f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
            styles["subtitle"]
        )
    )

    story.append(Spacer(1, 16))

    if not notes_data:
        story.append(
            Paragraph(
                "No notes were found.",
                styles["normal"]
            )
        )

    for note in notes_data:
        title = note.get("title") or "Untitled Note"
        content = note.get("content") or ""

        story.append(
            Paragraph(
                _safe_text(title),
                styles["section"]
            )
        )

        story.append(
            Paragraph(
                _safe_text(content),
                styles["normal"]
            )
        )

        created_at = note.get("created_at")

        if created_at:
            story.append(
                Paragraph(
                    f"Created: {_safe_text(created_at)}",
                    styles["italic"]
                )
            )

        story.append(Spacer(1, 10))

    doc.build(
        story,
        onFirstPage=_add_footer,
        onLaterPages=_add_footer,
    )

    buffer.seek(0)

    return buffer


