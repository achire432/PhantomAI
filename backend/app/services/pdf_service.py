def _safe_text(value) -> str:
    """
    Convert a value to safe text for ReportLab Paragraph.

    ReportLab Paragraph supports a small amount of XML-like
    markup, so user-generated content must be escaped first.
    """
    if value is None:
        return ""

    return escape(str(value)).replace("\n", "<br/>")


def _create_document(buffer: BytesIO) -> SimpleDocTemplate:
    """
    Create a standard PhantomAI PDF document.
    """
    return SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=54,
        leftMargin=54,
        topMargin=54,
        bottomMargin=54,
        title="PhantomAI Report",
        author="PhantomAI",
    )


def _get_styles():
    """
    Create shared PDF styles.
    """
    styles = getSampleStyleSheet()

    return {
        "title": ParagraphStyle(
            "PhantomTitle",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#1a3a6e"),
            spaceAfter=10,
        ),

        "subtitle": ParagraphStyle(
            "PhantomSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=colors.grey,
            spaceAfter=4,
        ),

        "section": ParagraphStyle(
            "PhantomSection",
            parent=styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=13,
            leading=16,
            textColor=colors.HexColor("#1a3a6e"),
            spaceBefore=8,
            spaceAfter=6,
        ),

        "normal": ParagraphStyle(
            "PhantomNormal",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10.5,
            leading=15,
            textColor=colors.HexColor("#222222"),
            alignment=TA_LEFT,
            spaceAfter=6,
        ),

        "user_label": ParagraphStyle(
            "UserLabel",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=10,
            textColor=colors.HexColor("#1a3a6e"),
            spaceAfter=3,
        ),

        "assistant_label": ParagraphStyle(
            "AssistantLabel",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=10,
            textColor=colors.HexColor("#333333"),
            spaceAfter=3,
        ),

        "message": ParagraphStyle(
            "Message",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            leftIndent=12,
            rightIndent=6,
            textColor=colors.HexColor("#222222"),
            spaceAfter=8,
        ),

        "italic": ParagraphStyle(
            "PhantomItalic",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=9,
            textColor=colors.grey,
            spaceAfter=6,
        ),
    }


def _add_footer(canvas, doc):
    """
    Add a simple footer to every page.
    """
    canvas.saveState()

    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.grey)

    canvas.drawString(
        doc.leftMargin,
        30,
        "Generated by PhantomAI"
    )

    canvas.drawRightString(
        letter[0] - doc.rightMargin,
        30,
        f"Page {doc.page}"
    )

    canvas.restoreState()


