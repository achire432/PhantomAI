def generate_tasks_pdf(tasks_data: list) -> BytesIO:
    """
    Generate a PDF from tasks.

    Expected structure:

    [
        {
            "title": "Task 1",
            "status": "pending",
            "priority": "high",
            "due_date": "2026-08-10"
        }
    ]

    Returns:
        BytesIO containing the generated PDF.
    """

    buffer = BytesIO()
    doc = _create_document(buffer)
    styles = _get_styles()

    story = []

    # Header
    story.append(
        Paragraph(
            "My Tasks",
            styles["title"]
        )
    )

    story.append(
        Paragraph(
            f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
            styles["subtitle"]
        )
    )

    story.append(Spacer(1, 16))

    # --------------------------------------------------------
    # Table
    # --------------------------------------------------------

    table_data = [
        [
            Paragraph("<b>Task</b>", styles["normal"]),
            Paragraph("<b>Status</b>", styles["normal"]),
            Paragraph("<b>Priority</b>", styles["normal"]),
            Paragraph("<b>Due Date</b>", styles["normal"]),
        ]
    ]

    for task in tasks_data or []:

        title = _safe_text(task.get("title", ""))
        status = _safe_text(task.get("status", "pending"))
        priority = _safe_text(task.get("priority", "medium"))

        due_date = task.get("due_date")

        if due_date:
            due_date = str(due_date)[:10]
        else:
            due_date = ""

        table_data.append(
            [
                Paragraph(title, styles["normal"]),
                Paragraph(status, styles["normal"]),
                Paragraph(priority, styles["normal"]),
                Paragraph(due_date, styles["normal"]),
            ]
        )

    if len(table_data) == 1:
        table_data.append(
            [
                Paragraph("No tasks found.", styles["normal"]),
                "",
                "",
                "",
            ]
        )

    table = Table(
        table_data,
        colWidths=[230, 85, 85, 85],
        repeatRows=1,
        hAlign="LEFT",
    )

    table.setStyle(
        TableStyle(
            [
                # Header
                (
                    "BACKGROUND",
                    (0, 0),
                    (-1, 0),
                    colors.HexColor("#1a3a6e"),
                ),
                (
                    "TEXTCOLOR",
                    (0, 0),
                    (-1, 0),
                    colors.white,
                ),
                (
                    "FONTNAME",
                    (0, 0),
                    (-1, 0),
                    "Helvetica-Bold",
                ),

                # Alignment
                (
                    "VALIGN",
                    (0, 0),
                    (-1, -1),
                    "TOP",
                ),

                # Padding
                (
                    "LEFTPADDING",
                    (0, 0),
                    (-1, -1),
                    6,
                ),
                (
                    "RIGHTPADDING",
                    (0, 0),
                    (-1, -1),
                    6,
                ),
                (
                    "TOPPADDING",
                    (0, 0),
                    (-1, -1),
                    7,
                ),
                (
                    "BOTTOMPADDING",
                    (0, 0),
                    (-1, -1),
                    7,
                ),

                # Borders
                (
                    "GRID",
                    (0, 0),
                    (-1, -1),
                    0.5,
                    colors.HexColor("#cccccc"),
                ),

                # Body
                (
                    "BACKGROUND",
                    (0, 1),
                    (-1, -1),
                    colors.white,
                ),
            ]
        )
    )

    story.append(table)

    doc.build(
        story,
        onFirstPage=_add_footer,
        onLaterPages=_add_footer,
    )

    buffer.seek(0)

    return buffer

from io import BytesIO

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.enums import TA_CENTER
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
)
from reportlab.lib.units import mm


def generate_file_pdf(
    file_name: str,
    file_path: str,
    content: str,
):
    """
    Generate a PDF containing extracted file content.
    """

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm,
    )

    styles = getSampleStyleSheet()

    title_style = styles["Title"]
    title_style.alignment = TA_CENTER

    body_style = styles["BodyText"]
    body_style.leading = 15

    story = []

    story.append(
        Paragraph(
            "PhantomAI File Export",
            title_style,
        )
    )

    story.append(
        Spacer(1, 12)
    )

    story.append(
        Paragraph(
            f"<b>File:</b> {file_name}",
            body_style,
        )
    )

    story.append(
        Paragraph(
            f"<b>Path:</b> {file_path}",
            body_style,
        )
    )

    story.append(
        Spacer(1, 15)
    )

    # Split content into paragraphs
    paragraphs = content.split("\n")

    for paragraph in paragraphs:
        clean_text = (
            paragraph
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
        )

        if clean_text.strip():
            story.append(
                Paragraph(
                    clean_text,
                    body_style,
                )
            )

            story.append(
                Spacer(1, 6)
            )

    document.build(story)

    buffer.seek(0)

    return buffer