def generate_conversation_pdf(conversation_data: dict) -> BytesIO:
    """
    Generate a PDF from a conversation.

    Expected structure:

    {
        "title": "My Chat",
        "messages": [
            {
                "role": "user",
                "content": "Hello"
            },
            {
                "role": "assistant",
                "content": "Hello! How can I help?"
            }
        ],
        "created_at": "2026-08-04"
    }

    Returns:
        BytesIO containing the generated PDF.
    """

    buffer = BytesIO()
    doc = _create_document(buffer)
    styles = _get_styles()

    story = []

    # --------------------------------------------------------
    # Header
    # --------------------------------------------------------

    title = conversation_data.get("title") or "Conversation"

    story.append(
        Paragraph(
            _safe_text(title),
            styles["title"]
        )
    )

    story.append(
        Paragraph(
            f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
            styles["subtitle"]
        )
    )

    created_at = conversation_data.get("created_at")

    if created_at:
        story.append(
            Paragraph(
                f"Started: {_safe_text(created_at)}",
                styles["subtitle"]
            )
        )

    story.append(Spacer(1, 16))

    # --------------------------------------------------------
    # Messages
    # --------------------------------------------------------

    messages = conversation_data.get("messages") or []

    if not messages:
        story.append(
            Paragraph(
                "No messages were found in this conversation.",
                styles["normal"]
            )
        )

    for message in messages:
        role = message.get("role", "unknown")
        content = message.get("content", "")

        if role == "user":
            label = "You"
            label_style = styles["user_label"]

        elif role == "assistant":
            label = "PhantomAI"
            label_style = styles["assistant_label"]

        else:
            label = str(role).capitalize()
            label_style = styles["assistant_label"]

        story.append(
            Paragraph(
                f"<b>{_safe_text(label)}</b>",
                label_style
            )
        )

        story.append(
            Paragraph(
                _safe_text(content),
                styles["message"]
            )
        )

        story.append(Spacer(1, 5))

    # --------------------------------------------------------
    # End
    # --------------------------------------------------------

    story.append(Spacer(1, 12))

    story.append(
        Paragraph(
            "End of Conversation",
            styles["italic"]
        )
    )

    doc.build(
        story,
        onFirstPage=_add_footer,
        onLaterPages=_add_footer,
    )

    buffer.seek(0)

    return buffer


